let language: Language = 'zh-CN';
try { if (localStorage.getItem('qwen-desk-language') === 'en') language = 'en'; } catch { /* Storage may be unavailable in previews. */ }

export function getLanguage(): Language { return language; }
export function setLanguage(value: Language): void {
  language = value;
  document.documentElement.lang = value;
  try { localStorage.setItem('qwen-desk-language', value); } catch { /* Backend settings remain authoritative. */ }
}
export function t(source: string): string { return language === 'en' ? messages[source] ?? source : source; }
export function localized(zh: string, en: string): string { return language === 'en' ? en : zh; }

// Translate only authored template segments. Interpolated model names, paths,
// user input and inference output are never searched or replaced.
const phrases = Object.keys(messages).sort((a, b) => b.length - a.length);
const templatePattern = new RegExp(phrases.map(s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
export function html(parts: TemplateStringsArray, ...values: unknown[]): string {
  return parts.reduce((result, part, index) => result + (language === 'en' ? part.replace(templatePattern, match => messages[match]) : part) + (index < values.length ? String(values[index] ?? '') : ''), '');
}
